DROP TABLE IF EXISTS conversation_item;
DROP TABLE IF EXISTS chat_conversation;
DROP TABLE IF EXISTS chat_project;
DROP TABLE IF EXISTS auth_session;
DROP TABLE IF EXISTS llm_request_record;
DROP TABLE IF EXISTS app_user;

CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    display_name VARCHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL,
    role VARCHAR(16) NOT NULL DEFAULT 'USER',
    created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE chat_project (
    id CHAR(36) PRIMARY KEY,
    user_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_chat_project_user
        FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE
);

CREATE TABLE chat_conversation (
    id CHAR(36) PRIMARY KEY,
    user_id BIGINT NOT NULL,
    project_id CHAR(36),
    title VARCHAR(200) NOT NULL,
    created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_message_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_chat_conversation_user
        FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_chat_conversation_project
        FOREIGN KEY (project_id) REFERENCES chat_project (id) ON DELETE SET NULL
);

CREATE TABLE conversation_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id CHAR(36) NOT NULL,
    sequence_no INTEGER NOT NULL,
    item_type VARCHAR(32) NOT NULL,
    role VARCHAR(16) NOT NULL,
    payload JSON NOT NULL,
    created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_conversation_item_sequence
        UNIQUE (conversation_id, sequence_no),
    CONSTRAINT fk_conversation_item_conversation
        FOREIGN KEY (conversation_id) REFERENCES chat_conversation (id) ON DELETE CASCADE,
    CONSTRAINT chk_conversation_item_type
        CHECK (item_type IN ('MESSAGE', 'TOOL_CALL', 'TOOL_RESULT')),
    CONSTRAINT chk_conversation_item_role
        CHECK (role IN ('USER', 'ASSISTANT', 'SYSTEM', 'TOOL'))
);

CREATE TABLE auth_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP(3) NOT NULL,
    created_at TIMESTAMP(3) NOT NULL,
    last_used_at TIMESTAMP(3) NOT NULL,
    revoked_at TIMESTAMP(3),
    CONSTRAINT fk_auth_session_user
        FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE
);

CREATE TABLE llm_request_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    request_id VARCHAR(64) NOT NULL UNIQUE,
    provider VARCHAR(32) NOT NULL,
    model VARCHAR(128) NOT NULL,
    result_status VARCHAR(16) NOT NULL,
    prompt_tokens INTEGER,
    completion_tokens INTEGER,
    total_tokens INTEGER,
    latency_ms BIGINT NOT NULL,
    upstream_status_code SMALLINT,
    error_code VARCHAR(64),
    error_message VARCHAR(512),
    requested_at TIMESTAMP(3) NOT NULL,
    CONSTRAINT fk_llm_request_record_user
        FOREIGN KEY (user_id) REFERENCES app_user (id)
);
